/**
 * Prepara os artefactos necessários para migrar de SQLite para PostgreSQL.
 *
 *   npm run db:prepare-postgres
 *
 * Gera prisma/postgresql/schema.prisma e uma migração inicial PostgreSQL.
 * Nada é aplicado a nenhum servidor: a migração real exige uma connection
 * string e deve ser testada primeiro num ambiente de ensaio.
 */
import { execSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const raiz = process.cwd();
const schemaOrigem = path.join(raiz, 'prisma', 'schema.prisma');
const pastaPostgres = path.join(raiz, 'prisma', 'postgresql');
const schemaDestino = path.join(pastaPostgres, 'schema.prisma');
const pastaMigracao = path.join(pastaPostgres, 'migrations', '20261111000000_inicial');

let schema = readFileSync(schemaOrigem, 'utf8');
if (!schema.includes('provider = "sqlite"')) {
  console.error('O schema de origem não está configurado para SQLite.');
  process.exit(1);
}

schema = schema.replace('provider = "sqlite"', 'provider = "postgresql"');
mkdirSync(pastaMigracao, { recursive: true });
writeFileSync(schemaDestino, schema, 'utf8');

console.log('A gerar a migração inicial PostgreSQL...');
const sql = execSync(
  `npx prisma migrate diff --from-empty --to-schema-datamodel "${schemaDestino}" --script`,
  { cwd: raiz, encoding: 'utf8' },
).replace(/^\uFEFF/, '');

writeFileSync(path.join(pastaMigracao, 'migration.sql'), sql, 'utf8');
writeFileSync(
  path.join(pastaPostgres, 'migrations', 'migration_lock.toml'),
  '# Please do not edit this file manually\nprovider = "postgresql"\n',
  'utf8',
);

const readme = `# PostgreSQL

Artefactos gerados por \`npm run db:prepare-postgres\`. A aplicação continua a
usar SQLite em desenvolvimento; esta pasta prepara a migração futura.

## Antes de migrar

1. Crie uma base PostgreSQL e defina \`DATABASE_URL\` com a connection string.
2. Faça uma cópia de segurança da base SQLite e dos uploads (\`npm run db:backup\`).
3. Teste todo o processo num ambiente de ensaio, nunca diretamente em produção.
4. Confirme que os ficheiros em \`public/uploads\` também serão migrados.

## Aplicar o schema

\`\`\`bash
npx prisma migrate deploy --schema prisma/postgresql/schema.prisma
npx prisma generate --schema prisma/postgresql/schema.prisma
\`\`\`

## Migrar os dados

Exporte os dados da SQLite e importe-os para PostgreSQL com uma ferramenta de
ETL ou um script dedicado. Preserve os identificadores (\`id\`) e as relações.
Depois de importar, execute o seed apenas se a base estiver vazia:

\`\`\`bash
DATABASE_URL="postgresql://..." npx tsx prisma/seed.ts
\`\`\`

## Notas

- Os backups passam a ser feitos com \`pg_dump\`, não com \`VACUUM INTO\`.
- A aplicação e o cliente Prisma devem ser gerados a partir do schema PostgreSQL.
- Mantenha a migração SQLite enquanto a migração não estiver concluída.
`;

writeFileSync(path.join(pastaPostgres, 'README.md'), readme, 'utf8');

console.log('');
console.log('Artefactos PostgreSQL criados:');
console.log('  prisma/postgresql/schema.prisma');
console.log('  prisma/postgresql/migrations/20261111000000_inicial/migration.sql');
console.log('  prisma/postgresql/README.md');
console.log('Nenhuma base de dados foi alterada.');
